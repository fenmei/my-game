// Sound Controller using ffmpeg generated audio in public/sounds/ with Web Audio fallback
class SoundController {
  constructor() {
    this.ctx = null;
    this.enabled = true;

    // Use import.meta.env.BASE_URL so audio paths work locally and on GitHub Pages
    const baseUrl = import.meta.env.BASE_URL || '/';
    const cleanBase = baseUrl.endsWith('/') ? baseUrl : `${baseUrl}/`;

    if (typeof window !== 'undefined') {
      this.matchAudio = new Audio(`${cleanBase}sounds/match.mp3`);
      this.victoryAudio = new Audio(`${cleanBase}sounds/victory.mp3`);
    }
  }

  init() {
    if (!this.ctx && typeof window !== 'undefined') {
      const AudioCtx = window.AudioContext || window.webkitAudioContext;
      if (AudioCtx) {
        this.ctx = new AudioCtx();
      }
    }
    if (this.ctx && this.ctx.state === 'suspended') {
      this.ctx.resume();
    }
  }

  setEnabled(val) {
    this.enabled = val;
  }

  // Soft wooden click / card swoosh
  playFlip() {
    if (!this.enabled) return;
    this.init();
    if (!this.ctx) return;

    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    osc.type = 'sine';
    const now = this.ctx.currentTime;
    osc.frequency.setValueAtTime(320, now);
    osc.frequency.exponentialRampToValueAtTime(700, now + 0.08);

    gain.gain.setValueAtTime(0.15, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.08);

    osc.connect(gain);
    gain.connect(this.ctx.destination);

    osc.start(now);
    osc.stop(now + 0.09);
  }

  // Short crisp "叮" sound generated by ffmpeg
  playMatch() {
    if (!this.enabled) return;
    if (this.matchAudio) {
      this.matchAudio.currentTime = 0;
      this.matchAudio.play().catch(() => {
        this.playSynthesizedMatch();
      });
    } else {
      this.playSynthesizedMatch();
    }
  }

  // 3-note ascending victory melody generated by ffmpeg
  playVictory() {
    if (!this.enabled) return;
    if (this.victoryAudio) {
      this.victoryAudio.currentTime = 0;
      this.victoryAudio.play().catch(() => {
        this.playSynthesizedVictory();
      });
    } else {
      this.playSynthesizedVictory();
    }
  }

  // Gentle low double tone when cards don't match
  playMismatch() {
    if (!this.enabled) return;
    this.init();
    if (!this.ctx) return;

    const now = this.ctx.currentTime;
    [260, 200].forEach((freq, idx) => {
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(freq, now + idx * 0.12);

      gain.gain.setValueAtTime(0.12, now + idx * 0.12);
      gain.gain.exponentialRampToValueAtTime(0.001, now + idx * 0.12 + 0.15);

      osc.connect(gain);
      gain.connect(this.ctx.destination);

      osc.start(now + idx * 0.12);
      osc.stop(now + idx * 0.12 + 0.16);
    });
  }

  playSynthesizedMatch() {
    this.init();
    if (!this.ctx) return;

    const osc = this.ctx.createOscillator();
    const gain = this.ctx.createGain();

    osc.type = 'sine';
    const now = this.ctx.currentTime;
    osc.frequency.setValueAtTime(1046.5, now); // C6

    gain.gain.setValueAtTime(0.3, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.4);

    osc.connect(gain);
    gain.connect(this.ctx.destination);

    osc.start(now);
    osc.stop(now + 0.42);
  }

  playSynthesizedVictory() {
    this.init();
    if (!this.ctx) return;

    const notes = [
      { f: 523.25, d: 0.2 }, // C5
      { f: 659.25, d: 0.2 }, // E5
      { f: 1046.5, d: 0.6 }, // C6
    ];

    let timeOffset = 0;
    const now = this.ctx.currentTime;

    notes.forEach((note) => {
      const osc = this.ctx.createOscillator();
      const gain = this.ctx.createGain();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(note.f, now + timeOffset);

      gain.gain.setValueAtTime(0.3, now + timeOffset);
      gain.gain.exponentialRampToValueAtTime(0.001, now + timeOffset + note.d);

      osc.connect(gain);
      gain.connect(this.ctx.destination);

      osc.start(now + timeOffset);
      osc.stop(now + timeOffset + note.d + 0.05);

      timeOffset += note.d * 0.9;
    });
  }
}

export const soundManager = new SoundController();
